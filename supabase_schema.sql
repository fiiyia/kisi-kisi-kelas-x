-- 1. Buat tabel utama untuk menyimpan seluruh data isian dan progres murid Kelas X
CREATE TABLE IF NOT EXISTS public.hasil_latihan_uas_x (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL UNIQUE,
  nama_lengkap TEXT NOT NULL,
  kelas TEXT NOT NULL CHECK (kelas IN ('X-1', 'X-2', 'X-3', 'X-4')),
  no_absen INTEGER NOT NULL DEFAULT 0,
  mode_latihan TEXT NOT NULL CHECK (mode_latihan IN ('belajar', 'simulasi')),
  is_submitted BOOLEAN NOT NULL DEFAULT FALSE,

  -- Rincian Skor per Bagian & Total (0 - 100)
  -- Bagian I: maks 30, Bagian II: maks 20, Bagian III: maks 50
  skor_bagian_1 INTEGER NOT NULL DEFAULT 0,
  skor_bagian_2 INTEGER NOT NULL DEFAULT 0,
  skor_bagian_3 INTEGER NOT NULL DEFAULT 0,
  total_skor INTEGER NOT NULL DEFAULT 0,

  -- Rincian Skor per Topik Materi (Eksponen & Logaritma: maks 30, SPtLDV: maks 50, Persamaan Kuadrat: maks 20)
  skor_eksponen_logaritma INTEGER NOT NULL DEFAULT 0,
  skor_sptldv INTEGER NOT NULL DEFAULT 0,
  skor_persamaan_kuadrat INTEGER NOT NULL DEFAULT 0,

  -- Seluruh Data Isian Murid (Format JSONB)
  jawaban_bagian_1 JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_2 JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_3_teks JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_3_rubrik JSONB NOT NULL DEFAULT '{}'::jsonb,

  -- Pencatatan Waktu
  waktu_mulai TIMESTAMPTZ,
  waktu_selesai TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 1B. Pastikan kolom no_absen & is_submitted tersedia jika tabel sudah dibuat sebelumnya
ALTER TABLE public.hasil_latihan_uas_x
  ADD COLUMN IF NOT EXISTS no_absen INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.hasil_latihan_uas_x
  ADD COLUMN IF NOT EXISTS is_submitted BOOLEAN NOT NULL DEFAULT FALSE;

-- 2. Buat indeks untuk mempercepat filter berdasarkan kelas, absen, dan waktu pengumpulan
CREATE INDEX IF NOT EXISTS idx_hasil_latihan_uas_x_kelas_absen ON public.hasil_latihan_uas_x (kelas, no_absen);
CREATE INDEX IF NOT EXISTS idx_hasil_latihan_uas_x_created_at ON public.hasil_latihan_uas_x (created_at DESC);

-- 3. Trigger otomatis untuk memperbarui kolom updated_at saat murid mengetik / mencentang rubrik
CREATE OR REPLACE FUNCTION public.set_updated_at_hasil_latihan_uas_x()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_hasil_latihan_uas_x_updated_at ON public.hasil_latihan_uas_x;
CREATE TRIGGER trg_hasil_latihan_uas_x_updated_at
BEFORE UPDATE ON public.hasil_latihan_uas_x
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at_hasil_latihan_uas_x();

-- 4. Aktifkan Row Level Security (RLS) dan izinkan akses anon key untuk simpan, update & muat ulang progres
ALTER TABLE public.hasil_latihan_uas_x ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Izinkan murid kelas X menyimpan hasil latihan (INSERT)" ON public.hasil_latihan_uas_x;
CREATE POLICY "Izinkan murid kelas X menyimpan hasil latihan (INSERT)"
  ON public.hasil_latihan_uas_x
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Izinkan murid kelas X memperbarui rubrik mandiri (UPDATE)" ON public.hasil_latihan_uas_x;
CREATE POLICY "Izinkan murid kelas X memperbarui rubrik mandiri (UPDATE)"
  ON public.hasil_latihan_uas_x
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Izinkan pembacaan data hasil latihan kelas X (SELECT)" ON public.hasil_latihan_uas_x;
CREATE POLICY "Izinkan pembacaan data hasil latihan kelas X (SELECT)"
  ON public.hasil_latihan_uas_x
  FOR SELECT
  TO anon, authenticated
  USING (true);
